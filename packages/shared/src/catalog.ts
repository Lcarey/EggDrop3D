import type {
  MaterialDefinition,
  MaterialId,
  MaterialPhysics,
  Vec3,
} from "./contracts.js";

const DEFAULT_PHYSICS = {
  friction: 0.55,
  restitution: 0.15,
  linearDamping: 0.08,
  angularDamping: 0.12,
  dragCoefficient: 1.05,
  cushioning: 0,
  buoyancyFactor: 0,
  breakForceN: 160,
} as const satisfies Omit<MaterialPhysics, "densityKgM3">;

function material(
  definition: Omit<MaterialDefinition, "physics"> & {
    physics: Pick<MaterialPhysics, "densityKgM3"> & Partial<MaterialPhysics>;
  },
): MaterialDefinition {
  return {
    ...definition,
    defaultDimensions: [...definition.defaultDimensions] as Vec3,
    physics: { ...DEFAULT_PHYSICS, ...definition.physics },
  };
}

