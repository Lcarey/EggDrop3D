export const MATERIAL_BY_ID: Readonly<Record<MaterialId, MaterialDefinition>> =
  Object.freeze(
    Object.fromEntries(MATERIAL_CATALOG.map((item) => [item.id, item])) as Record<
      MaterialId,
      MaterialDefinition
    >,
  );

export function getMaterial(materialId: MaterialId): MaterialDefinition {
  return MATERIAL_BY_ID[materialId];
}
